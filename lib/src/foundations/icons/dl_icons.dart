class DlPlaceholderIcon extends StatelessWidget {
  const DlPlaceholderIcon({super.key, this.size = 24, this.color});

  final double size;
  final Color? color;

  @override
  Widget build(BuildContext context) {
    final effectiveColor = color ?? IconTheme.of(context).color;
    return SvgPicture.asset(
      DlIcons.placeholderAsset,
      width: size,
      height: size,
      colorFilter: effectiveColor == null
          ? null
          : ColorFilter.mode(effectiveColor, BlendMode.srcIn),
    );
  }
}

class DlAssetIcon extends StatelessWidget {
  const DlAssetIcon({
    required this.assetPath,
    super.key,
    this.size = 24,
    this.color,
    this.preserveColors = false,
  });

  final String assetPath;
  final double size;
  final Color? color;
  final bool preserveColors;

  @override
  Widget build(BuildContext context) {
    if (preserveColors) {
      return SvgPicture.asset(
        assetPath,
        width: size,
        height: size,
      );
    }

    final effectiveColor = color ?? IconTheme.of(context).color;

    return SvgPicture.asset(
      assetPath,
      width: size,
      height: size,
      colorFilter: effectiveColor == null
          ? null
          : ColorFilter.mode(effectiveColor, BlendMode.srcIn),
    );
  }
}
