      c800: DlColorsDark.indigo800,
      c900: DlColorsDark.indigo900,
      c950: DlColorsDark.indigo950,
    ),
  );

  static DlColorPalette fallbackForBrightness(Brightness brightness) {
    return brightness == Brightness.dark ? dark : light;
  }

  @override
  DlColorPalette copyWith() => this;

  @override
  DlColorPalette lerp(covariant ThemeExtension<DlColorPalette>? other, double t) {
    if (other is! DlColorPalette) return this;
    return t < 0.5 ? this : other;
  }
}

extension DlColorPaletteContext on BuildContext {
  DlColorPalette get dlColors {
    final theme = Theme.of(this);
    return theme.extension<DlColorPalette>() ??
        DlColorPalette.fallbackForBrightness(theme.brightness);
  }
}
